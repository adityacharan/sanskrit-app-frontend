import { toIAST } from "./iast";
import { capFirst } from "./data";

export type BookItem = {
  id: string;
  deva: string;
  translit: string;
  meaning: string;
  kind: "word" | "sentence";
};
export type BookUnit = { id: string; no: number; deva: string; title: string; items: BookItem[] };

// A line with no ।, ? or ! and at most two words is a word ("अधिकारी", "लोकयानेन"); the rest are sentences.
const kindOf = (deva: string): BookItem["kind"] => (/[।?!]/.test(deva) || deva.split(" ").length > 2 ? "sentence" : "word");

const unit = (id: string, no: number, deva: string, title: string, rows: [string, string][]): BookUnit => ({
  id,
  no,
  deva,
  title,
  items: rows.map(([d, meaning], i) => {
    const kind = kindOf(d);
    return {
      id: `book:${id}:${i}`,
      deva: d,
      translit: toIAST(d),
      // Words are shown like the vocabulary cards: capitalised, no full stop.
      meaning: kind === "word" ? capFirst(meaning).replace(/\.$/, "") : meaning,
      kind,
    };
  }),
});

